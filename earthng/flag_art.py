"""The flags of the world's countries, for the flagpoles (generator.lua BLD.pinStreet 'flagpole').

  python earthng/flag_art.py --fetch          # earthng/flags/<code>.png from flagcdn.com (once)
  python earthng/flag_art.py --lua            # mod/lua/ge/extensions/e2r/flag_lib.lua
  python earthng/flag_art.py --sheet out/flags.png

A pole tagged country=XX flies that country's flag: a cell of one atlas (fast_style 'flags'),
PER x PER cells of CELL px, a flag stretched to its cell and drawn as wide as its own
proportion (flag_lib.lua has each code's cell and width to height). The countries are the
members of the United Nations and its two observer states, without Russia (the user's rule,
24.11.2026). The pictures are Flagpedia's (flagcdn.com, public domain), kept in earthng/flags so a
build needs no network; the atlas is made at art build, nothing paid.
"""
import argparse
from pathlib import Path
import time
import urllib.request

from PIL import Image

HERE = Path(__file__).resolve().parent
SOURCE = HERE / 'flags'
LUA = HERE.parent / 'mod/lua/ge/extensions/e2r/flag_lib.lua'
URL = 'https://flagcdn.com/w320/{code}.png'
VERSION = '1'           # change whenever a flag's picture or its cell changes
PER, CELL = 16, (256, 128)
PAD = 4                 # px of a cell round its flag, the flag's own edge drawn out (mips)
REF = 128               # the alpha a flag is cut by (Nepal's is no rectangle)
# ISO 3166-1 alpha-2: the 193 members of the United Nations, then the Holy See and Palestine
MEMBERS = '''af al dz ad ao ag ar am au at az bs bh bd bb by be bz bj bt bo ba bw br bn bg bf bi cv kh cm ca cf td cl cn co
km cg cd cr ci hr cu cy cz dk dj dm do ec eg sv gq er ee sz et fj fi fr ga gm ge de gh gr gd gt gn gw gy ht hn hu is in id
ir iq ie il it jm jp jo kz ke ki kp kr kw kg la lv lb ls lr ly li lt lu mg mw my mv ml mt mh mr mu mx fm md mc mn me ma mz
mm na nr np nl nz ni ne ng mk no om pk pw pa pg py pe ph pl pt qa ro ru rw kn lc vc ws sm st sa sn rs sc sl sg sk si sb so
za ss es lk sd sr se ch sy tj tz th tl tg to tt tn tr tm tv ug ua ae gb us uy uz vu ve vn ye zm zw'''.split()
OBSERVERS = ['va', 'ps']
LEFT_OUT = {'ru'}
# a flag keeps its cell by its place here: new codes go at the end
CODES = [c for c in MEMBERS + OBSERVERS if c not in LEFT_OUT]


def fetch(emit=print):
    """The pictures that are not in earthng/flags yet."""
    SOURCE.mkdir(exist_ok=True)
    got = 0
    for code in CODES:
        path = SOURCE / f'{code}.png'
        if path.exists() and path.stat().st_size > 100:
            continue
        request = urllib.request.Request(URL.format(code=code), headers={'User-Agent': 'flag-atlas-builder'})
        with urllib.request.urlopen(request, timeout=30) as reply:
            data = reply.read()
        if data[:8] != b'\x89PNG\r\n\x1a\n':
            raise RuntimeError(f'{code}: not a PNG')
        tmp = path.with_suffix('.tmp')
        tmp.write_bytes(data)
        tmp.replace(path)
        got += 1
        time.sleep(.05)
    emit(f'flags: {got} fetched, {len(CODES)} in {SOURCE}')
    return got


def ready():
    return all((SOURCE / f'{code}.png').exists() for code in CODES)


def aspects():
    """{code: width / height of its picture}."""
    out = {}
    for code in CODES:
        with Image.open(SOURCE / f'{code}.png') as im:
            out[code] = round(im.width / im.height, 3)
    return out


def sheet():
    """The atlas, row 0 at the top: (colour RGB, alpha L)."""
    w, h = CELL
    colour = Image.new('RGB', (PER * w, PER * h), (255, 255, 255))
    alpha = Image.new('L', (PER * w, PER * h), 0)
    for k, code in enumerate(CODES):
        x, y = (k % PER) * w, (k // PER) * h
        flag = Image.open(SOURCE / f'{code}.png').convert('RGBA')
        # the whole cell first, so the pad carries the flag's own edge; then the flag inside it
        for size, at in (((w, h), (x, y)), ((w - 2 * PAD, h - 2 * PAD), (x + PAD, y + PAD))):
            part = flag.resize(size, Image.LANCZOS)
            colour.paste(part.convert('RGB'), at)
            alpha.paste(part.getchannel('A'), at)
    return colour, alpha


def build(r):
    """flags.color.png and flags_o.data.png in the art folder r, flipped like the glyphs so v grows
    upward. Without the pictures nothing is written (the poles fly drawn stripes)."""
    if not ready():
        return False
    colour, alpha = sheet()
    colour.transpose(Image.FLIP_TOP_BOTTOM).save(r / 'flags.color.png')
    alpha.convert('RGB').transpose(Image.FLIP_TOP_BOTTOM).save(r / 'flags_o.data.png')
    (r / 'flags.version').write_text(VERSION)
    return True


def lua_text():
    """flag_lib.lua: the atlas's grid and each code's cell and proportion."""
    shape = aspects()
    rows = [f"  {code.upper()} = {{{k}, {shape[code]:g}}}," for k, code in enumerate(CODES)]
    return ('-- Generated by earthng/flag_art.py --lua: do not edit. The flags atlas (fast_style \'flags\'):\n'
            '-- per x per cells, a flag inside its cell by pad (a share of the cell, across and up);\n'
            '-- cells[CODE] = {cell from the top-left, the flag\'s width over its height}.\n'
            f"return {{version = '{VERSION}', per = {PER}, pad = {{{PAD / CELL[0]:g}, {PAD / CELL[1]:g}}}, count = {len(CODES)},\n"
            ' cells = {\n' + '\n'.join(rows) + '\n }}\n')


def main():
    p = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    p.add_argument('--fetch', action='store_true', help='download the pictures that are missing')
    p.add_argument('--lua', action='store_true', help='write flag_lib.lua')
    p.add_argument('--sheet', type=Path, help='write the atlas as one picture, to look at')
    a = p.parse_args()
    if a.fetch:
        fetch()
    if a.lua:
        LUA.write_text(lua_text(), encoding='utf8', newline='\n')
        print(LUA)
    if a.sheet:
        colour, alpha = sheet()
        colour.putalpha(alpha)
        a.sheet.parent.mkdir(parents=True, exist_ok=True)
        colour.save(a.sheet)
        print(a.sheet)


if __name__ == '__main__':
    main()
