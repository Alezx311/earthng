"""Write src/pytext_tables.rs: Python's own re \\w, str.casefold(), str.isspace() and decimal digits
(this interpreter's Unicode), so retail._key and float() in Rust read text exactly as Python does.

    python rust/crates/cells/gen_unicode.py
"""
import re
import sys
import unicodedata
from pathlib import Path

word = re.compile(r'\w')
ranges, start = [], None
for c in range(0x110000 + 1):
    is_word = c < 0x110000 and not 0xD800 <= c <= 0xDFFF and word.match(chr(c)) is not None
    if is_word and start is None:
        start = c
    elif not is_word and start is not None:
        ranges.append((start, c - 1))
        start = None
folds = []
for c in range(0x110000):
    if 0xD800 <= c <= 0xDFFF:
        continue
    f = chr(c).casefold()
    if f != chr(c):
        folds.append((c, f))

zeros = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF and unicodedata.decimal(chr(c), None) == 0]
assert all(unicodedata.decimal(chr(z + k), None) == k for z in zeros for k in range(10))
spaces = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF and chr(c).isspace()]


def lit(s):
    return '"' + ''.join(f'\\u{{{ord(ch):x}}}' for ch in s) + '"'

out = [f'// Generated by gen_unicode.py from Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.',
       '// Do not edit: rerun the script.',
       f'pub const UNIDATA: &str = "{unicodedata.unidata_version}";',
       f'pub static WORD: [(u32, u32); {len(ranges)}] = [']
out += [f'    (0x{a:x}, 0x{b:x}),' for a, b in ranges]
out += ['];', f'pub static FOLD: [(u32, &str); {len(folds)}] = [']
out += [f'    (0x{c:x}, {lit(f)}),' for c, f in folds]
out += ['];', f'/// str.isspace()', f'pub static SPACE: [u32; {len(spaces)}] = [' + ', '.join(f'0x{c:x}' for c in spaces) + '];',
        '/// the zero of each run of ten decimal digits (unicodedata.decimal)',
        f'pub static DECIMAL_ZERO: [u32; {len(zeros)}] = [' + ', '.join(f'0x{c:x}' for c in zeros) + '];', '']
Path(__file__).with_name('src').joinpath('pytext_tables.rs').write_text('\n'.join(out), encoding='utf8')
print(len(ranges), 'word ranges,', len(folds), 'folds,', len(spaces), 'spaces,', len(zeros), 'digit runs')
